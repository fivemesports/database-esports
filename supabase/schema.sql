create table if not exists public.server_snapshots (
  id bigint generated by default as identity primary key,
  captured_at timestamptz not null default now(),
  server_id text not null,
  hostname text not null,
  players integer not null default 0 check (players >= 0),
  max_players integer not null default 0 check (max_players >= 0),
  country_code text null
);

-- Fast lookups for recent history and monthly country ranking queries.
create index if not exists server_snapshots_captured_at_idx
  on public.server_snapshots (captured_at desc);
create index if not exists server_snapshots_server_id_captured_at_idx
  on public.server_snapshots (server_id, captured_at desc);
create index if not exists server_snapshots_country_captured_at_idx
  on public.server_snapshots (country_code, captured_at desc);

-- Keep the table private. Only server-side API routes using the service-role
-- key can read/write it; never expose that key in NEXT_PUBLIC_* variables.
alter table public.server_snapshots enable row level security;

-- Monthly top 10 per country, ranked by average recorded concurrent players.
-- This view only reports months for which snapshots were actually collected.
create or replace view public.monthly_country_top10 as
with monthly as (
  select
    date_trunc('month', captured_at)::date as month,
    country_code,
    server_id,
    (array_agg(hostname order by captured_at desc))[1] as hostname,
    round(avg(players))::integer as avg_players,
    max(players) as peak_players,
    count(*)::bigint as sample_count
  from public.server_snapshots
  where country_code is not null
  group by date_trunc('month', captured_at)::date, country_code, server_id
), ranked as (
  select monthly.*,
    row_number() over (
      partition by month, country_code
      order by avg_players desc, peak_players desc, server_id
    ) as rank
  from monthly
)
select month, country_code, server_id, hostname, avg_players, peak_players, sample_count, rank
from ranked
where rank <= 10;

